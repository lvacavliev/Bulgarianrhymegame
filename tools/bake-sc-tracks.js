// Rimoboy: writes js/sc-tracks.js from the offline analysis (tools/sc-analysis.json).
// Usage: node tools/bake-sc-tracks.js [tools/sc-analysis.json]
// Applies tools/sc-overrides.json (reviewed drop corrections, in whole beats) on top.
// Keeps only the numbers the game needs: bpm, dropMs, endMs, and check (= the analysis
// flagged something: listen with "Чуй дропа" and fix it with the tap tool if needed).
'use strict';
const fs = require('fs');
const path = require('path');

const src = process.argv[2] || path.join(__dirname, 'sc-analysis.json');
const out = path.join(__dirname, '..', 'js', 'sc-tracks.js');
const data = JSON.parse(fs.readFileSync(src, 'utf8'));
// reviewed corrections: move the drop by whole beats, re-round the end to whole bars
const ovPath = path.join(__dirname, 'sc-overrides.json');
const overrides = fs.existsSync(ovPath) ? JSON.parse(fs.readFileSync(ovPath, 'utf8')) : {};
for (const [slug, o] of Object.entries(overrides)) {
  const r = data[slug];
  if (slug.startsWith('_')) continue;
  if (!r) { console.warn(`WARNING: override for unknown slug "${slug}" (not in ${path.basename(src)})`); continue; }
  if (!o.dropBeats) continue;
  const beat = 60000 / r.bpm, bar = 4 * beat;
  const drop = r.dropMs + o.dropBeats * beat;
  r.endMs = Math.round(drop + Math.floor((r.endMs - drop) / bar + 1e-6) * bar);
  r.dropMs = Math.round(drop);
  r.flags = (r.flags || []).concat([`drop moved ${o.dropBeats} beat(s) by review`]);
}

const lines = Object.keys(data).sort().map((slug) => {
  const r = data[slug];
  const fields = [`bpm: ${r.bpm}`, `dropMs: ${r.dropMs}`, `endMs: ${r.endMs}`];
  if (r.flags && r.flags.length) fields.push('check: true');
  const note = (r.flags && r.flags.length ? '  // ' + r.flags.join('; ') : '').replace(/\s+/g, ' ');
  return `    ${JSON.stringify(slug).padEnd(20)}: { ${fields.join(', ')} },${note}`;
});

const today = new Date().toISOString().slice(0, 10);
const js = `/* Rimoboy: beat data for the Bizzle Beats SoundCloud tracks. Spec: BUILD.md 8A.7.
   GENERATED by tools/bake-sc-tracks.js from tools/sc-analysis.json (${today}). Do not edit by
   hand: re-run tools/analyze_sc.py for new tracks, then the bake script.
   Measured offline from the audio (librosa), like the reference game's hand-made metadata:
   bpm    : constant tempo of the track
   dropMs : song position of the downbeat where the drums come in = bar 1 of the rapping
   endMs  : end of the full beat (whole bars after the drop); "Цялата песен" stops here
   check  : the analysis was not sure about something (see the comment): listen once with
            "Чуй дропа" and correct it with the tap tool if it is off.
   The user's own values (localStorage rb_scTempo) override this table. Tracks missing here
   (new uploads) fall back to the waveform guess of js/drop.js. */
(function () {
  'use strict';
  window.SC_TRACKS = {
${lines.join('\n')}
  };
})();
`;
fs.writeFileSync(out, js);
console.log(`wrote ${out}: ${lines.length} tracks`);
